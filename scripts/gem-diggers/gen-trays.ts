// Pre-generates every level's tray, in every difficulty mode, into
// src/pages/project/gem-diggers/trays.ts so the game never has to search for one while the player
// waits. Run after changing a level:
//   yarn gem:gen
// Entries are keyed by a fingerprint of the level as played, so unchanged
// levels are kept as they are (pass --all to redo everything).
//
// Each candidate tray is checked by replaying it with the real game rules
// (src/verify.ts); the winning tap order found is stored alongside it.
//
// Big hard-mode levels take minutes each, so the work can be split across
// processes: --levels=1,2,3 picks levels and --out=file writes just those
// results to a JSON file, to be merged into trays.ts afterwards;
// --attempts=N tries more candidates when a level comes out off target.

/* eslint-disable no-console -- a command-line tool: printing progress is its job */
import { writeFileSync } from 'node:fs'
import { buildBoard, trayOptions } from '../../src/pages/project/gem-diggers/game'
import {
  TrayLayout,
  generateCandidates,
  greedyWinRate,
  mulberry32,
  plainTray,
  trayKey,
} from '../../src/pages/project/gem-diggers/generator'
import { LEVELS } from '../../src/pages/project/gem-diggers/levels'
import { MODES, MODE_NAMES, applyMode } from '../../src/pages/project/gem-diggers/modes'
import { PREGENERATED_TRAYS } from '../../src/pages/project/gem-diggers/trays'
import { solveReal } from '../../src/pages/project/gem-diggers/verify'

const OUT = 'src/pages/project/gem-diggers/trays.ts' // yarn runs scripts from the project folder
const all = process.argv.includes('--all')
const arg = (name: string) =>
  process.argv.find((a) => a.startsWith(`--${name}=`))?.slice(name.length + 3)
const only = arg('mode')
const pickLevels = arg('levels')?.split(',').map(Number)
const partOut = arg('out')
const attemptsArg = arg('attempts')

type Entry = { layout: TrayLayout; solution: number[] }
// What trays.ts held when this script was bundled, i.e. just before it ran.
const existing: Record<string, Entry> = PREGENERATED_TRAYS

/** Source of trays.ts. The data is a JSON string so TypeScript doesn't infer a huge literal type. */
function traysModule(trays: Record<string, Entry>): string {
  return [
    '// Generated by `yarn gem:gen` (scripts/gem-diggers/gen-trays.ts): pre-built',
    '// trays for every level in every mode, each with a tap order that wins.',
    '// Kept as a JSON string so TypeScript does not have to infer a huge literal type.',
    '',
    "import type { TrayLayout } from './generator'",
    '',
    'export interface IPregeneratedTray {',
    '  layout: TrayLayout',
    '  solution: number[]',
    '}',
    '',
    'export const PREGENERATED_TRAYS: Record<string, IPregeneratedTray> = JSON.parse(',
    // Single-quoted, as Prettier would leave it (the JSON has no quotes or backslashes to escape).
    `  '${JSON.stringify(trays).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`,
    ')',
    '',
  ].join('\n')
}

const out: Record<string, Entry> = {}
const fresh: Record<string, Entry> = {} // generated in this run
let failed = 0
for (const mode of MODES) {
  LEVELS.forEach((base, i) => {
    const level = applyMode(base, mode)
    const tag = `[${MODE_NAMES[mode]}] ${String(i + 1).padStart(2)} ${level.name}`
    const seed = i + 1
    const key = trayKey(level, seed)
    if (
      (!all && existing[key]) ||
      (only && only !== mode) ||
      (pickLevels && !pickLevels.includes(i + 1))
    ) {
      if (existing[key]) out[key] = existing[key]
      return
    }
    const { board } = buildBoard(level)
    const t0 = performance.now()
    // Big maps cost far more per candidate, so try fewer of them.
    const huge = level.art.length * level.art[0].length > 800
    const attempts = attemptsArg ? Number(attemptsArg) : huge ? 40 : 200
    const opt = { ...trayOptions(level, seed), attempts, greedyRuns: huge ? 24 : 60 }
    // The quick estimate used while searching is noisy, so re-measure the
    // shortlist properly and keep the winnable one truly closest to the target.
    const candidates = [
      ...generateCandidates(board, opt, 6)
        .slice(0, 8)
        .map((c) => c.tray),
      plainTray(board, opt),
    ]
    let best: (Entry & { rate: number }) | null = null
    for (const layout of candidates) {
      const solution = solveReal(level, seed, layout)
      if (!solution) continue
      const rate = greedyWinRate(board, layout, opt, 200, mulberry32(seed))
      if (!best || Math.abs(rate - level.greedy) < Math.abs(best.rate - level.greedy))
        best = { layout, solution, rate }
    }
    if (!best) {
      failed++
      console.log(`${tag}: ERROR no tray the real game can win (${candidates.length} tried)`)
      return
    }
    out[key] = fresh[key] = { layout: best.layout, solution: best.solution }
    const carts = best.layout.columns.flat()
    console.log(
      `${tag}: ${level.art[0].length}x${level.art.length}, ${carts.length} carts (biggest ${Math.max(...carts.map((c) => c.count))}), ` +
        `no-planning win rate ${(best.rate * 100).toFixed(0)}% (target ${Math.round(level.greedy * 100)}%), ` +
        `won in ${best.solution.length} taps, ${((performance.now() - t0) / 1000).toFixed(1)}s`
    )
    // Save as we go: the hard mode takes a while.
    if (partOut) writeFileSync(partOut, JSON.stringify(fresh))
    else writeFileSync(OUT, traysModule({ ...existing, ...out }))
  })
}

if (partOut) {
  writeFileSync(partOut, JSON.stringify(fresh))
  console.log(`wrote ${Object.keys(fresh).length} trays to ${partOut}`)
} else {
  writeFileSync(OUT, traysModule(out))
  console.log(`wrote ${Object.keys(out).length} trays`)
}
if (failed) process.exit(1)
